"""SC-5 / D-10 / D-11 guards for the phase 04.1 training layout (no GPU, default suite)."""

from __future__ import annotations

import os
import subprocess
import tomllib
from pathlib import Path

from fc.train import paths

REPO = Path(__file__).resolve().parents[1]
TRAIN_ROOT = Path("/mnt/d/fc-train")
HF_CACHE = Path("/mnt/d/hf-cache")
TRAINING_PACKAGES = {
    "torch", "transformers", "trl", "peft", "bitsandbytes", "accelerate",
    "liger-kernel", "datasets", "unsloth",
}


def _under(path: Path, root: Path) -> bool:
    return path == root or root in path.parents


def test_path_constants_live_on_d_drive():
    skipped = {"REPO_ROOT", "REPO_DATA"}
    checked = 0
    for name, value in vars(paths).items():
        if name.startswith("_") or name in skipped or not isinstance(value, Path):
            continue
        assert _under(value, TRAIN_ROOT) or value == HF_CACHE, f"{name} = {value}"
        checked += 1
    assert checked >= 15


def test_env_paths_live_on_d_drive():
    values = paths.env()
    path_values = {k: v for k, v in values.items() if v.startswith("/")}
    assert {"UV_CACHE_DIR", "HF_HOME", "TMPDIR", "UV_PYTHON_INSTALL_DIR"} <= set(path_values)
    for key, value in path_values.items():
        assert value.startswith("/mnt/d/"), f"{key}={value}"


def test_env_sh_matches_shell_exports():
    on_disk = (REPO / "scripts" / "train" / "env.sh").read_text()
    assert on_disk == paths.shell_exports()
    assert on_disk.splitlines()[0].startswith("# Generated by `uv run python -m fc.train.paths")
    for name in ("FC_VENV_TRAIN", "FC_VENV_CONVERT", "FC_VENV_EVAL", "FC_VENV_UNSLOTH",
                 "FC_LLAMA_CPP_SRC", "FC_BASE_REPO", "FC_BASE_REVISION", "HF_HOME"):
        assert f"export {name}=" in on_disk


def test_pyproject_has_no_training_packages():
    data = tomllib.loads((REPO / "pyproject.toml").read_text())
    project = data["project"]
    specs = list(project.get("dependencies", []))
    for extra in project.get("optional-dependencies", {}).values():
        specs.extend(extra)
    names = set()
    for spec in specs:
        stem = spec
        for sep in ("[", "=", "<", ">", "!", "~", ";", " "):
            stem = stem.split(sep)[0]
        names.add(stem.strip().lower().replace("_", "-"))
    assert not names & TRAINING_PACKAGES, names & TRAINING_PACKAGES


def test_tracked_files_under_5mb():
    out = subprocess.run(
        ["git", "ls-files", "data/phase-04.1", "scripts/train"],
        cwd=REPO, capture_output=True, text=True, check=True).stdout.split()
    big = [f for f in out if (REPO / f).is_file() and os.path.getsize(REPO / f) > 5_000_000]
    assert not big, big
